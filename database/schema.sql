-- Schema fornecido pelo usuario, ordenado pelas dependencias das chaves estrangeiras.

-- Execute somente em um banco vazio. Nao ha DROP nem alteracao automatica de tabelas.

CREATE SCHEMA IF NOT EXISTS public;

CREATE TABLE public.api_clients (
	id bigserial NOT NULL,
	nome varchar(150) NOT NULL,
	client_id varchar(100) NOT NULL,
	contexto varchar(20) NOT NULL,
	token_hash char(64) NOT NULL,
	token_prefix varchar(24) NOT NULL,
	ativo bool DEFAULT true NOT NULL,
	expira_em timestamp NULL,
	rate_limit_per_minute int4 NULL,
	ultimo_acesso_em timestamp NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	atualizado_em timestamp DEFAULT CURRENT_TIMESTAMP NOT NULL,
	CONSTRAINT api_clients_pkey PRIMARY KEY (id),
	CONSTRAINT api_clients_client_id_key UNIQUE (client_id),
	CONSTRAINT api_clients_token_hash_key UNIQUE (token_hash),
	CONSTRAINT api_clients_contexto_check CHECK (contexto IN ('internal', 'third_party', 'development', 'temporary')),
	CONSTRAINT api_clients_rate_limit_check CHECK (rate_limit_per_minute IS NULL OR rate_limit_per_minute > 0)
);

CREATE TABLE public.api_client_scopes (
	api_client_id int8 NOT NULL,
	scope varchar(100) NOT NULL,
	CONSTRAINT api_client_scopes_pkey PRIMARY KEY (api_client_id, scope),
	CONSTRAINT api_client_scopes_client_fk FOREIGN KEY (api_client_id) REFERENCES public.api_clients(id) ON DELETE CASCADE
);

CREATE TABLE public.atributos (
	id bigserial NOT NULL,
	nome varchar(150) NOT NULL,
	tipo varchar(30) DEFAULT 'texto'::character varying NULL,
	unidade varchar(30) NULL,
	ativo bool DEFAULT true NULL,
	CONSTRAINT atributos_pkey PRIMARY KEY (id)
);

CREATE TABLE public.categorias (
	id bigserial NOT NULL,
	nome varchar(150) NOT NULL,
	descricao text NULL,
	categoria_pai_id int8 NULL,
	ativo bool DEFAULT true NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	atualizado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT categorias_pkey PRIMARY KEY (id),
	CONSTRAINT fk_categoria_pai FOREIGN KEY (categoria_pai_id) REFERENCES public.categorias(id) ON DELETE SET NULL
);

CREATE TABLE public.fornecedores (
	id bigserial NOT NULL,
	nome varchar(255) NOT NULL,
	razao_social varchar(255) NULL,
	cnpj varchar(20) NULL,
	email varchar(150) NULL,
	telefone varchar(30) NULL,
	cidade varchar(100) NULL,
	estado varchar(2) NULL,
	ativo bool DEFAULT true NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT fornecedores_pkey PRIMARY KEY (id)
);

CREATE TABLE public.marcas (
	id bigserial NOT NULL,
	nome varchar(150) NOT NULL,
	ativo bool DEFAULT true NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT marcas_nome_key UNIQUE (nome),
	CONSTRAINT marcas_pkey PRIMARY KEY (id)
);

CREATE TABLE public.plataformas (
	id bigserial NOT NULL,
	nome varchar(100) NOT NULL,
	ativo bool DEFAULT true NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT plataformas_nome_key UNIQUE (nome),
	CONSTRAINT plataformas_pkey PRIMARY KEY (id)
);

CREATE TABLE public.produtos (
	id int8 GENERATED BY DEFAULT AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 9223372036854775807 START 1 CACHE 1 NO CYCLE) NOT NULL,
	codigo int4 NULL,
	descricao varchar(512) NULL,
	marca varchar(512) NULL,
	preco int4 NULL,
	saldo varchar(512) NULL,
	CONSTRAINT produtos_pkey PRIMARY KEY (id)
);

CREATE TABLE public.produtos_plataformas (
	id bigserial NOT NULL,
	codigo varchar(50) NOT NULL,
	codigo_barras varchar(50) NULL,
	descricao varchar(255) NOT NULL,
	descricao_completa text NULL,
	categoria_id int8 NULL,
	marca_id int8 NULL,
	modelo varchar(150) NULL,
	unidade varchar(20) DEFAULT 'UN'::character varying NULL,
	peso numeric(10, 3) NULL,
	altura numeric(10, 2) NULL,
	largura numeric(10, 2) NULL,
	comprimento numeric(10, 2) NULL,
	ativo bool DEFAULT true NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	atualizado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	preco numeric(14, 2) DEFAULT 0 NULL,
	CONSTRAINT produtos_plataformas_codigo_key UNIQUE (codigo),
	CONSTRAINT produtos_plataformas_pkey PRIMARY KEY (id),
	CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES public.categorias(id) ON DELETE SET NULL,
	CONSTRAINT fk_produto_marca FOREIGN KEY (marca_id) REFERENCES public.marcas(id) ON DELETE SET NULL
);

CREATE TABLE public.estoques (
	id bigserial NOT NULL,
	produto_id int8 NOT NULL,
	quantidade numeric(14, 3) DEFAULT 0 NULL,
	reservado numeric(14, 3) DEFAULT 0 NULL,
	estoque_minimo numeric(14, 3) DEFAULT 0 NULL,
	estoque_maximo numeric(14, 3) NULL,
	atualizado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT estoques_pkey PRIMARY KEY (id),
	CONSTRAINT estoques_produto_id_key UNIQUE (produto_id),
	CONSTRAINT fk_estoque_produto FOREIGN KEY (produto_id) REFERENCES public.produtos_plataformas(id) ON DELETE CASCADE
);

CREATE TABLE public.logs_integracao (
	id bigserial NOT NULL,
	plataforma_id int8 NULL,
	produto_id int8 NULL,
	tipo varchar(50) NULL,
	status varchar(30) NULL,
	mensagem text NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT logs_integracao_pkey PRIMARY KEY (id),
	CONSTRAINT fk_log_plataforma FOREIGN KEY (plataforma_id) REFERENCES public.plataformas(id) ON DELETE SET NULL,
	CONSTRAINT fk_log_produto FOREIGN KEY (produto_id) REFERENCES public.produtos(id) ON DELETE SET NULL
);

CREATE TABLE public.movimentacoes_estoque (
	id bigserial NOT NULL,
	produto_id int8 NOT NULL,
	tipo varchar(30) NOT NULL,
	quantidade numeric(14, 3) NOT NULL,
	saldo_anterior numeric(14, 3) NULL,
	saldo_posterior numeric(14, 3) NULL,
	referencia varchar(150) NULL,
	observacao text NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT ck_tipo_movimentacao CHECK (((tipo)::text = ANY ((ARRAY['ENTRADA'::character varying, 'VENDA'::character varying, 'DEVOLUCAO'::character varying, 'AJUSTE_POSITIVO'::character varying, 'AJUSTE_NEGATIVO'::character varying, 'TRANSFERENCIA'::character varying])::text[]))),
	CONSTRAINT movimentacoes_estoque_pkey PRIMARY KEY (id),
	CONSTRAINT fk_mov_produto FOREIGN KEY (produto_id) REFERENCES public.produtos(id) ON DELETE RESTRICT
);

CREATE TABLE public.produto_atributos (
	id bigserial NOT NULL,
	produto_id int8 NOT NULL,
	atributo_id int8 NOT NULL,
	valor varchar(255) NOT NULL,
	CONSTRAINT produto_atributos_pkey PRIMARY KEY (id),
	CONSTRAINT uq_produto_atributo UNIQUE (produto_id, atributo_id),
	CONSTRAINT fk_pa_atributo FOREIGN KEY (atributo_id) REFERENCES public.atributos(id) ON DELETE CASCADE,
	CONSTRAINT fk_pa_produto FOREIGN KEY (produto_id) REFERENCES public.produtos(id) ON DELETE CASCADE
);

CREATE TABLE public.produto_fornecedor (
	id bigserial NOT NULL,
	produto_id int8 NOT NULL,
	fornecedor_id int8 NOT NULL,
	codigo_fornecedor varchar(100) NULL,
	preco_custo numeric(14, 2) NULL,
	principal bool DEFAULT false NULL,
	CONSTRAINT produto_fornecedor_pkey PRIMARY KEY (id),
	CONSTRAINT uq_produto_fornecedor UNIQUE (produto_id, fornecedor_id),
	CONSTRAINT fk_pf_fornecedor FOREIGN KEY (fornecedor_id) REFERENCES public.fornecedores(id) ON DELETE CASCADE,
	CONSTRAINT fk_pf_produto FOREIGN KEY (produto_id) REFERENCES public.produtos(id) ON DELETE CASCADE
);

CREATE TABLE public.produto_plataforma (
	id bigserial NOT NULL,
	produto_id int8 NOT NULL,
	plataforma_id int8 NOT NULL,
	codigo_externo varchar(150) NULL,
	titulo_externo varchar(255) NULL,
	preco numeric(14, 2) NULL,
	quantidade_publicada numeric(14, 3) NULL,
	ativo bool DEFAULT true NULL,
	sincronizado bool DEFAULT false NULL,
	ultima_sincronizacao timestamp NULL,
	criado_em timestamp DEFAULT CURRENT_TIMESTAMP NULL,
	CONSTRAINT produto_plataforma_pkey PRIMARY KEY (id),
	CONSTRAINT uq_produto_plataforma UNIQUE (produto_id, plataforma_id),
	CONSTRAINT fk_pp_plataforma FOREIGN KEY (plataforma_id) REFERENCES public.plataformas(id) ON DELETE CASCADE,
	CONSTRAINT fk_pp_produto FOREIGN KEY (produto_id) REFERENCES public.produtos(id) ON DELETE CASCADE
);

CREATE INDEX idx_produtos_codigo ON public.produtos USING btree (codigo);

CREATE INDEX idx_produtos_descricao ON public.produtos USING btree (descricao);
